create table account (
    id bigint generated by default as identity primary key,
    email varchar(255) not null,
    password_hash varchar(255) not null,
    role varchar(32) not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    created_by varchar(255),
    updated_by varchar(255),
    constraint uk_account_email unique (email)
);

create table author (
    id bigint generated by default as identity primary key,
    name varchar(200) not null,
    biography varchar(4000),
    created_at timestamp not null,
    updated_at timestamp not null,
    created_by varchar(255),
    updated_by varchar(255)
);

create table category (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    description varchar(1000),
    created_at timestamp not null,
    updated_at timestamp not null,
    created_by varchar(255),
    updated_by varchar(255),
    constraint uk_category_name unique (name)
);

create table book (
    id bigint generated by default as identity primary key,
    title varchar(200) not null,
    isbn varchar(20) not null,
    description varchar(4000),
    publication_year integer not null,
    rating numeric(3, 2) not null,
    category_id bigint not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    created_by varchar(255),
    updated_by varchar(255),
    search_vector tsvector GENERATED ALWAYS AS (
        (
            setweight(to_tsvector('english'::regconfig, (COALESCE(title, ''::character varying))::text), 'A'::"char") ||
            setweight(to_tsvector('english'::regconfig, (COALESCE(description, ''::character varying))::text), 'B'::"char"))
        ) STORED,
    constraint uk_book_isbn unique (isbn),
    constraint fk_book_category foreign key (category_id) references category(id)
);

create table book_author (
    book_id bigint not null,
    author_id bigint not null,
    primary key (book_id, author_id),
    constraint fk_book_author_book foreign key (book_id) references book(id),
    constraint fk_book_author_author foreign key (author_id) references author(id)
);

create table refresh_token (
    id uuid primary key,
    account_id bigint not null,
    token_hash varchar(255) not null,
    expires_at timestamp not null,
    revoked_at timestamp,
    replaced_by_token_id uuid,
    last_used_at timestamp,
    created_at timestamp not null,
    updated_at timestamp not null,
    created_by varchar(255),
    updated_by varchar(255),
    constraint fk_refresh_token_account foreign key (account_id) references account(id)
);

create index idx_author_name on author(name);
create index idx_book_title on book(title);
create index idx_book_publication_year on book(publication_year);
create index idx_book_rating on book(rating);
create index idx_refresh_token_account_id on refresh_token(account_id);
create index idx_book_search_gin on public.book using gin (search_vector);